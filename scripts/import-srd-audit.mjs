/**
 * THE SRD AUDIT CHASSIS MAP — generated from Christopher's audit document.
 *
 *   node scripts/import-srd-audit.mjs <audit.md> <out.ts>
 *
 * RULE 1: a file Christopher hands over IS the truth. The audit walked all 330 SRD 5.2.1 stat
 * blocks on printed pages 258-364 and published CR, size, type, AC and base HP for every one, plus
 * the new pricing primitives each needs. Where our PDF parse and this document disagree, THE
 * DOCUMENT WINS — it read the printed pages, the parser read a text layer that loses digits.
 *
 * ⚠ THIS IS A CHASSIS MAP, NOT A CREATURE LIBRARY. It carries the header line and nothing else:
 * no traits, no actions, no damage. It can COMPLETE a parsed creature and it can PROVE one is
 * absent, but it can never stand in for one — a creature with AC and HP and no actions would price
 * at zero DPR, which is a wrong answer wearing the shape of an answer.
 *
 * Re-run this whenever the audit document is revised. Do not hand-edit the output.
 */

import { readFileSync, writeFileSync } from "node:fs";

const [, , SRC, OUT] = process.argv;
if (!SRC || !OUT) {
  console.error("usage: node scripts/import-srd-audit.mjs <audit.md> <out.ts>");
  process.exit(2);
}

const ROW = /^\|\s*(\d+)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*(\d+)\s*\|\s*(\d+)\s*\|\s*([^|]*?)\s*\|$/;

const rows = [];
for (const raw of readFileSync(SRC, "utf8").split("\n")) {
  const m = raw.replace(/\r$/, "").match(ROW);
  if (!m) continue;
  const primitives = m[8] === "—" || m[8] === "-" ? [] : m[8].split(",").map(s => s.trim()).filter(Boolean);
  rows.push({
    page: Number(m[1]), name: m[2], cr: m[3], size: m[4],
    creatureType: m[5], ac: Number(m[6]), hp: Number(m[7]), primitives,
  });
}

if (rows.length === 0) {
  console.error("no chassis rows matched — has the table format changed?");
  process.exit(1);
}

// The CR 26-30 estimator rows (M28) live in their own table and are read by the estimator, not by
// the creature library. Same document, same authority, so they are lifted here too.
const CR_ROW = /^\|\s*(2[6-9]|30)\s*\|\s*(\d+)\s*\|\s*(\d+)\s*\|\s*(\d+)-(\d+)\s*\|\s*(\d+)\s*\|\s*(\d+)-(\d+)\s*\|\s*(\d+)\s*\|$/;
const crRows = [];
for (const raw of readFileSync(SRC, "utf8").split("\n")) {
  const m = raw.replace(/\r$/, "").match(CR_ROW);
  if (!m) continue;
  crRows.push({
    cr: Number(m[1]), proficiencyBonus: Number(m[2]), expectedAc: Number(m[3]),
    hpLow: Number(m[4]), hpHigh: Number(m[5]), expectedAttackBonus: Number(m[6]),
    dprLow: Number(m[7]), dprHigh: Number(m[8]), expectedSaveDc: Number(m[9]),
  });
}

const primitiveCount = new Set(rows.flatMap(r => r.primitives)).size;

const header = `/**
 * SRD 5.2.1 AUDIT CHASSIS MAP — generated. Do not hand-edit.
 *
 * ⚠ GENERATED by \`scripts/import-srd-audit.mjs\` from Christopher's
 * \`SRD_5.2.1_creature_pricing_mechanics_audit.md\`, which walked all ${rows.length} stat blocks on
 * printed pages 258-364. RULE 1: that document is the authority. Where it and our PDF parse
 * disagree, it wins — it read the printed pages; the parser read a text layer that drops digits.
 *
 * ⚠ HEADER LINE ONLY. No traits, no actions, no damage. This COMPLETES a parsed creature and
 * PROVES an absent one; it can never stand in for one. A creature with AC and HP and no actions
 * prices at zero DPR, which is a wrong answer wearing the shape of an answer.
 *
 * ${rows.length} chassis rows · ${primitiveCount} distinct new/extended primitives · ${crRows.length} CR 26-30 estimator rows.
 */

/** One SRD stat block's header line, as the audit published it. */
export type SrdAuditChassis = {
  /** Printed page in the SRD, so a disagreement can be checked against the source. */
  page: number;
  name: string;
  /** As printed — "1/8", "0", "21". Kept as text because CR is not a number in the general case. */
  cr: string;
  size: string;
  creatureType: string;
  ac: number;
  hp: number;
  /** M01-M28: the pricing primitives this block needs beyond the workbook's current set. */
  primitives: string[];
};

/** One row of the CR 26-30 extension the audit specifies as M28. */
export type SrdAuditCrRow = {
  cr: number;
  proficiencyBonus: number;
  expectedAc: number;
  hpLow: number;
  hpHigh: number;
  expectedAttackBonus: number;
  dprLow: number;
  dprHigh: number;
  expectedSaveDc: number;
};

export const SRD_AUDIT_CHASSIS: SrdAuditChassis[] = ${JSON.stringify(rows, null, 1)};

export const SRD_AUDIT_CR_ROWS: SrdAuditCrRow[] = ${JSON.stringify(crRows, null, 1)};

export const SRD_AUDIT_BY_NAME = new Map(SRD_AUDIT_CHASSIS.map(c => [c.name, c]));
`;

writeFileSync(OUT, header, "utf8");
console.log(`[srd-audit] ${rows.length} chassis rows, ${crRows.length} CR rows -> ${OUT}`);
